-- Windows that should always be floating and pinned across workspaces.
-- Add an entry here; the loop below applies the same treatment to each.
-- Hyprland sizes a window as if tiled before floating it (regression since the
-- 0.53 windowrule rework), so without an explicit size these open at whatever
-- the tile would have been. Override `size` per entry; defaults to the below.
-- NB: hyprwm/Hyprland#16446 reports size/move being ignored for floating
-- windows on 0.56.2 + Lua config, so this may be inert until that's fixed.
local defaultFloatSize = "900 600"

local floatPinned = {
	{
		name = "firefox-pip",
		match = { class = "^firefox$", initial_title = "^Picture-in-Picture$" },
		size = "640 360",
	},
	{ name = "bluetooth-pip", match = { class = "^blueman-manager$" } },
}

for _, rule in ipairs(floatPinned) do
	hl.window_rule({
		name = rule.name,
		match = rule.match,

		float = true,
		pin = true,
		size = rule.size or defaultFloatSize,
	})
end

